#!/usr/bin/env python3
"""RF2 sign-off (Phase A, 2026-10-29): runs every RF2 head step and check in order and writes STATUS_RF2.md + out/rf2_signoff.json. A board is re-routed only
when its netlist definition changed (hash stored in its check file) unless --cold. MODELED / tool-checked: no fabricator DRC, no CAM review, no bench.
usage (repo root): python3 experiments/RF2_cleansheet/head/rf2_signoff.py [--cold]      (also: make rf2-signoff)"""
import os, sys, json, subprocess, hashlib, time
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.abspath(os.path.join(HERE, "..", "..", "..")); OUT = os.path.join(HERE, "out")
sys.path.insert(0, HERE); import rf2_netlist as NL
COLD = "--cold" in sys.argv; PY = sys.executable
def run(args, t=3600):
    t0 = time.time(); r = subprocess.run([PY] + args, cwd=ROOT, capture_output=True, text=True, timeout=t); return r.returncode, round(time.time() - t0, 1), (r.stdout + r.stderr)[-400:]
def bhash(b): return hashlib.sha256(json.dumps(NL.BOARDS[b], sort_keys=True, default=str).encode() + open(os.path.join(HERE, "rf2_boards.py"), "rb").read()).hexdigest()[:16]
def main():
    steps = []
    def step(name, args, result_json=None, okkey="ok"):
        rc, s, tail = run(args); ok = rc == 0
        if result_json and os.path.exists(result_json):
            d = json.load(open(result_json)); ok = ok and bool(d.get(okkey, True) if not callable(okkey) else okkey(d))
        steps.append(dict(step=name, rc=rc, seconds=s, ok=ok, tail=tail if not ok else "")); print(f"{'OK  ' if ok else 'FAIL'} {name} {s}s", flush=True)
    H = "experiments/RF2_cleansheet/head/"
    step("netlist consistency", [H + "rf2_netlist.py"])
    step("housing + seats (STL, spec)", [H + "rf2_head.py"])
    step("SH1 shield board", [H + "rf2_shield_pcb.py"], os.path.join(OUT, "SH1/sh1_check.json"), lambda d: d["kicad_drc_errors"] == 0 and d["kicad_unconnected"] == 0 and d["topology"]["loop_free"])
    if os.path.exists(os.path.join(ROOT, "work/kit_v22/sbq_geometry.json")): step("SB1R-QA/QB outline variant", [H + "rf2_sb1r_variant.py"], os.path.join(OUT, "SB1R_RF2/sb1r_variant_check.json"))
    else: steps.append(dict(step="SB1R-QA/QB outline variant", ok=False, rc=None, seconds=0, tail="work/ not set up: run make setup and the sbq-fast step"))
    todo = []
    for b in ("TXJ", "MP1", "LR1"):
        cj = os.path.join(OUT, b, f"{b.lower()}_check.json")
        if COLD or not os.path.exists(cj) or json.load(open(cj)).get("netlist_hash") != bhash(b): todo.append(b)
    if todo: step(f"boards routed + checked ({', '.join(todo)})", [H + "rf2_boards.py"] + todo)
    for b in ("TXJ", "MP1", "LR1"):
        cj = os.path.join(OUT, b, f"{b.lower()}_check.json")
        if os.path.exists(cj):
            d = json.load(open(cj)); d["netlist_hash"] = bhash(b) if d.get("ok") else None; json.dump(d, open(cj, "w"), indent=1)
            steps.append(dict(step=f"board {b}: placement, route, KiCad DRC, copper, parity, Gerbers", ok=bool(d.get("ok")), rc=0, seconds=0,
                              tail="" if d.get("ok") else json.dumps({k: v.get("ok") for k, v in d.items() if isinstance(v, dict)})))
    step("field code cross-check (magpylib vs loop_B)", [H + "rf2_field_xcheck.py"], os.path.join(OUT, "rf2_field_xcheck.json"))
    if os.path.exists(os.path.join(ROOT, H, "rf2_mp1_spice.py")): step("MP1 protection study (ngspice)", [H + "rf2_mp1_spice.py"])
    step("REF3 sizing", [H + "rf2_ref3.py"], os.path.join(OUT, "rf2_ref3.json"), lambda d: d["chosen"] is not None)
    step("housing checks (meshes, envelope, interference, seats, clearances)", [H + "rf2_head_check.py"], os.path.join(OUT, "rf2_head_check.json"))
    step("wiring / power / timing (slot probes)", [H + "rf2_wiring.py"], os.path.join(OUT, "rf2_wiring.json"), lambda d: d["checks"]["ok"])
    step("volume ledger", [H + "rf2_ledger.py"], os.path.join(OUT, "rf2_ledger.json"))
    step("parity: built boards + harness vs netlist", [H + "rf2_parity.py"], os.path.join(OUT, "rf2_parity.json"))
    par = json.load(open(os.path.join(OUT, "rf2_parity.json"))) if os.path.exists(os.path.join(OUT, "rf2_parity.json")) else {}
    res = dict(status="RF2 sign-off: MODELED / tool-checked (no fabricator DRC, CAM review or bench)", ok=all(s["ok"] for s in steps), steps=steps,
               harness_pending=[p["id"] for p in par.get("harness", {}).get("pending_phase_c", [])])
    json.dump(res, open(os.path.join(OUT, "rf2_signoff.json"), "w"), indent=1)
    L = ["# RF2 head sign-off status (generated by rf2_signoff.py; MODELED / tool-checked)", "", f"Overall: **{'PASS' if res['ok'] else 'FAIL'}**", "", "| Step | Result | s |", "|---|---|---|"]
    L += [f"| {s['step']} | {'PASS' if s['ok'] else 'FAIL'} | {s['seconds']} |" for s in steps]
    L += ["", f"Harness conductors still pending (an end on a Phase C board, the neck driver or the coil): {', '.join(res['harness_pending']) or 'none'}.",
          "Not covered yet: AB1A / AB1B rework, CB1D routing, the neck driver, the rigid-flex panel, real 3D component models, fabricator DRC, bench."]
    open(os.path.join(HERE, "..", "STATUS_RF2.md"), "w").write("\n".join(L) + "\n"); print("overall", "PASS" if res["ok"] else "FAIL")
if __name__ == "__main__": main()
