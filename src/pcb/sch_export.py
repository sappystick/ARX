#!/usr/bin/env python3
"""KiCad schematics (.kicad_sch) generated from the board netlists (OPEN_ITEMS 9). The netlist is the source of truth: every part becomes a
box symbol with its real pin numbers and pin names, and every pin carries a local net label, so the schematic has exactly the netlist's
connectivity (labels with the same name are connected in KiCad). sch_check() re-reads each .kicad_sch, rebuilds the nets from the label
positions and compares them with the netlist node by node. Readability is a grid of parts, not a hand-drawn circuit; the PNG schematics in
docs/figures remain the reading copy. KiCad's own ERC has not been run on these files (no KiCad here)."""
import re, os, sys, json, math, uuid, glob

def parse_net(path):
    t = open(path).read(); comps = {}
    for m in re.finditer(r'\(comp \(ref "([^"]+)"\) \(value "([^"]*)"\)(?: \(footprint "([^"]*)"\))?', t): comps[m[1]] = dict(value=m[2], footprint=m[3] or "")
    nets = {}
    for m in re.finditer(r'\(net \(code "?\d+"?\) \(name "([^"]+)"\)(.*?)(?=\(net \(code|\)\s*\)\s*$)', t, re.S):
        nets[m[1]] = [(a, b, c or b) for a, b, c in re.findall(r'\(node \(ref "([^"]+)"\) \(pin "([^"]+)"\)(?: \(pinfunction "([^"]*)"\))?', m[2])]
    return comps, nets

def nkey(s): return [int(x) if x.isdigit() else x for x in re.split(r'(\d+)', s)]
G, PL, W = 2.54, 2.54, 15.24                                    # grid, pin length, box width (mm)
def U(seed): return str(uuid.uuid5(uuid.NAMESPACE_URL, seed))   # stable uuids so regenerated files diff cleanly
def q(s): return s.replace("\\", "\\\\").replace('"', "'")

def layout(comps, nets):
    pins = {r: {} for r in comps}
    for n, nodes in nets.items():
        for r, p, f in nodes: pins.setdefault(r, {})[p] = f
    out = {}
    for r, ps in pins.items():
        order = sorted(ps, key=nkey); half = math.ceil(len(order) / 2); left, right = order[:half], order[half:]
        geo = {}
        for i, p in enumerate(left): geo[p] = (-W / 2 - PL, -(i * G), 0)          # symbol frame y-up; connection point, pin angle
        for i, p in enumerate(right): geo[p] = (W / 2 + PL, -(i * G), 180)
        out[r] = dict(pins=ps, geo=geo, h=max(1, half) * G)
    return out

def symbol_lib(ref, L):
    name = f"PF233_auto:{ref}"; h = L["h"]; o = [f'    (symbol "{name}" (pin_names (offset 0.5)) (exclude_from_sim no) (in_bom yes) (on_board yes)',
        f'      (property "Reference" "{ref}" (at 0 {G:.2f} 0) (effects (font (size 1.27 1.27))))', f'      (property "Value" "" (at 0 {-h - G:.2f} 0) (effects (font (size 1.27 1.27))))',
        f'      (property "Footprint" "" (at 0 0 0) (effects (font (size 1.27 1.27)) hide))', f'      (symbol "{ref}_0_1" (rectangle (start {-W/2:.2f} {G/2:.2f}) (end {W/2:.2f} {-h + G/2:.2f}) (stroke (width 0.254) (type default)) (fill (type background))))',
        f'      (symbol "{ref}_1_1"']
    for p, (x, y, a) in L["geo"].items(): o.append(f'        (pin passive line (at {x:.2f} {y:.2f} {a}) (length {PL}) (name "{q(L["pins"][p])}" (effects (font (size 1.0 1.0)))) (number "{q(p)}" (effects (font (size 1.0 1.0)))))')
    o.append("      )\n    )"); return "\n".join(o)

def export(board, netpath, outpath):
    comps, nets = parse_net(netpath); L = layout(comps, nets); refs = sorted(L, key=nkey)
    col_w, x0, y0, maxh = 63.5, 30.48, 30.48, 260.0; pos = {}; x, y = x0, y0
    for r in refs:
        h = L[r]["h"] + 2 * G
        if y + h > maxh: x += col_w; y = y0
        pos[r] = (x, y); y += h + G
    paper = "A1" if x + col_w < 820 else "A0"; root = U(board + "/root")
    o = [f'(kicad_sch (version 20231120) (generator "arx_sch_export") (generator_version "1") (uuid "{root}") (paper "{paper}")',
         f'  (title_block (title "PF233-{board} (generated from {os.path.basename(netpath)})") (comment 1 "Connectivity by net labels; generated by src/pcb/sch_export.py. Not checked with KiCad ERC."))', "  (lib_symbols"]
    o += [symbol_lib(r, L[r]) for r in refs]; o.append("  )")
    for r in refs:
        X, Y = pos[r]; c = comps.get(r, dict(value="", footprint=""))
        o.append(f'  (symbol (lib_id "PF233_auto:{r}") (at {X:.2f} {Y:.2f} 0) (unit 1) (exclude_from_sim no) (in_bom yes) (on_board yes) (dnp no) (uuid "{U(board+"/"+r)}")')
        o.append(f'    (property "Reference" "{r}" (at {X:.2f} {Y - G:.2f} 0) (effects (font (size 1.27 1.27))))')
        o.append(f'    (property "Value" "{q(c["value"])[:60]}" (at {X:.2f} {Y + L[r]["h"] + G/2:.2f} 0) (effects (font (size 1.0 1.0))))')
        o.append(f'    (property "Footprint" "{q(c["footprint"])}" (at {X:.2f} {Y:.2f} 0) (effects (font (size 1.27 1.27)) hide))')
        for p in L[r]["geo"]: o.append(f'    (pin "{q(p)}" (uuid "{U(board+"/"+r+"/"+p)}"))')
        o.append(f'    (instances (project "PF233-{board}" (path "/{root}" (reference "{r}") (unit 1))))\n  )')
    for n, nodes in nets.items():
        for r, p, f in nodes:
            px, py, a = L[r]["geo"][p]; X, Y = pos[r]; lx, ly = X + px, Y - py
            ang, just = (180, "right") if a == 0 else (0, "left")
            o.append(f'  (label "{q(n)}" (at {lx:.2f} {ly:.2f} {ang}) (fields_autoplaced yes) (effects (font (size 1.0 1.0)) (justify {just})) (uuid "{U(board+"/L/"+r+"/"+p)}"))')
    o.append(f'  (sheet_instances (path "/" (page "1")))\n)'); txt = "\n".join(o)
    assert txt.count("(") == txt.count(")"), "paren balance"; open(outpath, "w").write(txt)
    return dict(board=board, parts=len(refs), nets=len(nets), pins=sum(len(v) for v in nets.values()), paper=paper)

def sch_check(schpath, netpath):
    """rebuild nets from the schematic (symbol pin geometry + label positions) and compare with the netlist"""
    t = open(schpath).read(); _, nets = parse_net(netpath)
    libpins = {}
    for m in re.finditer(r'\(symbol "PF233_auto:([^"]+)" \(pin_names(.*?)\n    \)', t, re.S):
        libpins[m[1]] = {pn: (float(x), float(y)) for x, y, pn in re.findall(r'\(pin passive line \(at ([-\d.]+) ([-\d.]+) \d+\).*?\(number "([^"]+)"', m[2])}
    pts = {}
    for m in re.finditer(r'\(symbol \(lib_id "PF233_auto:([^"]+)"\) \(at ([-\d.]+) ([-\d.]+) 0\)', t):
        r, X, Y = m[1], float(m[2]), float(m[3])
        for pn, (x, y) in libpins[r].items(): pts[(round(X + x, 2), round(Y - y, 2))] = (r, pn)
    got = {}; stray = 0
    for n, x, y in re.findall(r'\(label "([^"]+)" \(at ([-\d.]+) ([-\d.]+) \d+\)', t):
        k = (round(float(x), 2), round(float(y), 2))
        if k in pts: got.setdefault(n, set()).add(pts[k])
        else: stray += 1
    want = {n: {(r, p) for r, p, _ in v} for n, v in nets.items()}
    diff = [n for n in set(want) | set(got) if want.get(n, set()) != got.get(n, set())]
    return dict(nets=len(want), nodes=sum(len(v) for v in want.values()), mismatched_nets=sorted(diff)[:10], stray_labels=stray, ok=not diff and stray == 0)

BOARDS = {  # board -> netlist (current generators first, legacy kits where no generator in the flow writes one)
    "CB1D": "kit_v18/CB1D/PF233-CB1D.net", "LB1": "kit_v18/LB1/PF233-LB1.net",
    "AB1A": "legacy/PHIFOLD233_FINAL_KIT_v3/04_PCB_receiver_AB1A/PF233-AB1A.net", "AB1B": "legacy/PHIFOLD233_FINAL_KIT_v3/05_PCB_receiver_AB1B/PF233-AB1B.net",
    "PB1R": "legacy/PHIFOLD233_KIT_v6_ARCHITECTURE/PB1R/PF233-PB1R.net", "PM1": "legacy/PHIFOLD233_FINAL_KIT_v4/03_POWER_BOARD_PM1/PF233-PM1.net",
    "HB1": "kit_v6/HB1/PF233-HB1.net"}                                   # make pcb-hb1 (digital trigger switch); the legacy HB1 netlist has the linear SS49E

if __name__ == "__main__":
    os.makedirs("kit_v22/SCH", exist_ok=True); res = {}
    for b, n in BOARDS.items():
        if not os.path.exists(n): res[b] = dict(skipped=f"netlist {n} not present (run the board's make target)"); print(b, res[b]); continue
        out = f"kit_v22/SCH/PF233-{b}.kicad_sch"; r = export(b, n, out); r["check"] = sch_check(out, n); res[b] = r; print(b, r)
    json.dump(res, open("kit_v22/sch_check.json", "w"), indent=1)
    print("FAILS", sum(1 for v in res.values() if "check" in v and not v["check"]["ok"]), "of", sum(1 for v in res.values() if "check" in v))
