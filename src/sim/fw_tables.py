#!/usr/bin/env python3
"""Generate the firmware constant tables and test vectors from the Python models, so the C firmware (fw/) and the references cannot drift apart.
Writes (work/kit_v23/): pf233_dsp_tables.h (gates, frame counts, weights, ground basis, tau bank and its 64 x 9 basis, class edges, LED pixel map) and
pf233_dsp_vectors.h (inputs and reference outputs of src/sim/dsp_ref.py for fw/tests/test_dsp.c). MODELED values; regenerated by the pipeline.
usage (in work/, after dsp_ref.py and output_modes.py): python3 fw_tables.py"""
import json, csv, math
import numpy as np
import dsp_ref as R
D = json.load(open("kit_v23/dsp_ref.json"))
def cf(x):
    """a C float literal: always with a decimal point or exponent; magnitudes under 1e-30 (below float range: phi of short tau in late gates) are 0"""
    x = float(x); x = 0.0 if abs(x) < 1e-30 else x; s = "%.9g" % x
    return (s if ("." in s or "e" in s) else s + ".0") + "f"
def arr(name, a, fmt=None, ctype="float"):
    a = np.asarray(a); f = cf if fmt is None else (lambda v: fmt % v)
    return f"static const {ctype} {name}[{len(a)}] = {{" + ", ".join(f(x) for x in a) + "};"
H = ["/* GENERATED by src/sim/fw_tables.py from src/sim/dsp_ref.py and the pixel map (MODELED). Do not edit: change the model and regenerate. */", "#pragma once",
     f"#define PF_NG {len(R.GATES)}", f"#define PF_NTAU {len(R.TAUS)}", f"#define PF_NCLASS {len(R.CLASSES)}",
     arr("PF_G0", R.GATES[:, 0]), arr("PF_G1", R.GATES[:, 1]), arr("PF_NK", R.NK), arr("PF_W", R.W), arr("PF_PSI", R.PSI), arr("PF_TAU", R.TAUS),
     "static const float PF_PHI[PF_NTAU][PF_NG] = {" + ", ".join("{" + ", ".join(cf(v) for v in row) + "}" for row in R.PHI) + "};",
     arr("PF_CLASS_HI", [hi for _, _, hi in R.CLASSES]),
     "/* class ids: " + ", ".join(f"{i} {c}" for i, (c, _, _) in enumerate(R.CLASSES)) + " */"]
pix = [r for r in csv.DictReader(open("kit_v18/SET/02_CORE_PCB_CYLINDER/PIXEL_MAP_66.csv"))]
H += [f"#define PF_NLED {len(pix)}", arr("PF_LED_RING", [int(p["ring"]) for p in pix], "%d", "unsigned char"), arr("PF_LED_AZ", [float(p["azimuth_deg"]) for p in pix])]
open("kit_v23/pf233_dsp_tables.h", "w").write("\n".join(H) + "\n")
V = D["vectors"]
L = ["/* GENERATED by src/sim/fw_tables.py: test vectors and reference outputs of src/sim/dsp_ref.py (fit_ridge). Do not edit. */", "#pragma once",
     f"#define PF_NVEC {len(V)}", "typedef struct { float gA[9], gB[9], bA, bB, sig0, sb, tau, aA, aB, axis, snr; int cls; } pf_vec_t;",
     "static const pf_vec_t PF_VEC[PF_NVEC] = {"]
cls_id = {c: i for i, (c, _, _) in enumerate(R.CLASSES)}
for v in V:
    L.append("  {{" + ", ".join(cf(x) for x in v["gA"]) + "}, {" + ", ".join(cf(x) for x in v["gB"]) + "}, " +
             ", ".join(cf(v[k]) for k in ("bA", "bB", "sig0", "sb", "tau", "aA", "aB", "axis", "snr")) + f", {cls_id[v['cls']]}" + "},")
L.append("};")
open("kit_v23/pf233_dsp_vectors.h", "w").write("\n".join(L) + "\n")
print("tables", len(H), "lines; vectors", len(V))
